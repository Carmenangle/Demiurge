"""生成桌面壳卸载钩子：把 `app.data_layout` 的三档口径编译成 NSIS 脚本。

跑：`python scripts/generate_uninstall_hooks.py`（写文件）
判漂移：`python scripts/generate_uninstall_hooks.py --check`（非零＝生成物过期）

产物 `desktop/tauri/installer/uninstall-hooks.nsh` 只实现 `NSIS_HOOK_POSTUNINSTALL`
（由 `tauri.conf.json` 的 `bundle.windows.nsis.installerHooks` 挂进 tauri 生成的 installer.nsi），
并被 `scripts/build_installers.py` 的静默安装/卸载核验消费。

四条硬规则（改这个脚本前先读）：
- 删除面只逐名取 `cache`/`settings`；产物、容器与未登记名字**永不出现在脚本里**，生成器对此断言。
- 不允许出现「删除整个壳 home」的指令，生成器对此断言。
- 更新（`$UpdateMode = 1`）时整段跳过：tauri 升级会先用旧版卸载器静默卸载，那时删 `runtime\\`
  等于每次升级重下 2.26 GB。
- 用到 `$UpdateMode` / `$DeleteAppDataCheckboxState`（由 tauri 模板声明）的代码必须写在
  **宏体内**：宏在 installer.nsi 的卸载段里展开（位置在两个 `Var` 之后），而顶层 `Function`
  在 `!include` 处编译——放顶层会在变量尚未声明时编译失败。
- 生成的 `.nsh` 必须纯 ASCII：NSIS 对非 ASCII 脚本的编码判定依赖 BOM，回执文案因此用英文。
  卸载完成的**用户可见文案**不在这里，它是 `installer/languages/<lang>.nsh` 里的 `LangString`
  （由 `generate_installer_languages.py` 生成），本文件只引用 `$(DemiurgeUninstKeep)` /
  `$(DemiurgeUninstWiped)` 并在其后拼上真实 home 路径。
- `MessageBox` 的参数顺序是 `MessageBox mode text [/SD return]`（本机 makensis 实测：`/SD` 写在
  mode 前面直接编译报错）。`/SD` 让静默卸载（`/S`，出包门禁与升级都走这条）跳过弹窗而不是挂住。
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app import data_layout  # noqa: E402

OUT = ROOT / "desktop" / "tauri" / "installer" / "uninstall-hooks.nsh"

#: scope → NSIS 里的相对前缀（`$DemiurgeShellHome` 在运行时解析壳 home）。
_PREFIX = {
    data_layout.SCOPE_SHELL_HOME: "$DemiurgeShellHome",
    data_layout.SCOPE_USERDATA: "$DemiurgeShellHome\\userdata",
}


def _remove(scope: str, name: str, tier: str, kind: str, counter: int) -> tuple[str, int]:
    """逐名删除块：存在才动，动完复查，OK/KEEP 都写回执（删不掉＝被占用，必须可见）。"""
    path = f"{_PREFIX[scope]}\\{name}"
    probe = f"{path}\\*.*" if kind == data_layout.DIR else path
    verb = "dir" if kind == data_layout.DIR else "file"
    n0 = counter
    gone, kept, skip = f"d{n0}", f"d{n0 + 1}", f"d{n0 + 2}"
    counter += 3
    lines = [
        f"  ; [{tier}] {scope}/{name} ({verb})",
        f'  IfFileExists "{probe}" 0 {skip}',
    ]
    lines.append('  RmDir /r "' + path + '"' if kind == data_layout.DIR else '  Delete "' + path + '"')
    lines += [
        f'  IfFileExists "{probe}" {kept} {gone}',
        f"  {gone}:",
        f'  StrCpy $R8 "OK    {scope}/{name}"',
        "  Call un.DemiurgeLog",
        f"  Goto {skip}",
        f"  {kept}:",
        f'  StrCpy $R8 "KEEP  {scope}/{name}"',
        "  Call un.DemiurgeLog",
        f"  {skip}:",
        "",
    ]
    return "\n".join(lines), counter


def _block(scope: str, tier: str, counter: int) -> tuple[str, int]:
    entries = [
        (name, meta[0], meta[1])
        for name, meta in sorted(data_layout.SCOPES[scope].items())
        if meta[0] == tier
    ]
    body = []
    for name, entry_tier, kind in entries:
        chunk, counter = _remove(scope, name, entry_tier, kind, counter)
        body.append(chunk)
    return "".join(body), counter


def _joined(parts: list[str]) -> str:
    text = "".join(parts).rstrip("\n")
    return text if text.strip() else "  ;（无）"


def render() -> str:
    counter = 0
    cache_parts: list[str] = []
    settings_parts: list[str] = []
    for scope in (data_layout.SCOPE_SHELL_HOME, data_layout.SCOPE_USERDATA):
        chunk, counter = _block(scope, data_layout.CACHE, counter)
        cache_parts.append(chunk)
    for scope in (data_layout.SCOPE_SHELL_HOME, data_layout.SCOPE_USERDATA):
        chunk, counter = _block(scope, data_layout.SETTINGS, counter)
        settings_parts.append(chunk)

    bak_lines = []
    for scope, stems in data_layout.SETTINGS_BACKUP_STEMS.items():
        for stem in stems:
            # Probe first: `Delete` with a wildcard matches nothing silently, and a receipt
            # line claiming a removal that never happened would be a lie.
            bak_lines.append(f'  IfFileExists "{_PREFIX[scope]}\\{stem}.bak-*" 0 demiurge_bak_{counter}')
            bak_lines.append(f'  Delete "{_PREFIX[scope]}\\{stem}.bak-*"')
            bak_lines.append(f'  StrCpy $R8 "BAK   {scope}/{stem}.bak-*"')
            bak_lines.append("  Call un.DemiurgeLog")
            bak_lines.append(f"  demiurge_bak_{counter}:")
            counter += 1
    bak = "\n".join(bak_lines)

    cache = _joined(cache_parts)
    settings = _joined(settings_parts)

    return f"""; Generated by scripts/generate_uninstall_hooks.py - do not edit.
; Source of truth: backend/app/data_layout.py (tiers: cache / settings / product).
; cache is always removed; settings only when "Delete the application data" is checked;
; product / container / unregistered names never appear here.
; ASCII only: NSIS decides script encoding from a BOM, and the receipt text must stay readable.
; The completion popup text is a LangString from the language override files; this script only
; references it and appends the resolved shell home, so an override of DEMIURGE_SHELL_HOME shows.

Var /GLOBAL DemiurgeShellHome
Var /GLOBAL DemiurgeUninstMsg

Function un.DemiurgeLog
  ; Append one line to uninstall.log in the shell home; DetailPrint only when home is absent.
  IfFileExists "$DemiurgeShellHome\\*.*" 0 un_demiurge_log_missing
  ClearErrors
  FileOpen $9 "$DemiurgeShellHome\\uninstall.log" a
  IfErrors un_demiurge_log_missing
  ; NSIS "a" opens at byte 0, so without this seek every line overwrites the previous one.
  FileSeek $9 0 END
  FileWrite $9 "$R8$\\r$\\n"
  FileClose $9
  un_demiurge_log_missing:
  DetailPrint "$R8"
  Return
FunctionEnd

!macro NSIS_HOOK_POSTUNINSTALL
  SetShellVarContext current
  ; Same rule as Rust paths::home(): DEMIURGE_SHELL_HOME wins over %LOCALAPPDATA%\\Demiurge.
  StrCpy $DemiurgeShellHome "$LOCALAPPDATA\\Demiurge"
  ReadEnvStr $0 DEMIURGE_SHELL_HOME
  StrCmp $0 "" demiurge_home_default
  StrCpy $DemiurgeShellHome $0
  demiurge_home_default:
  ; Updates re-run the old uninstaller silently: delete nothing in that mode.
  ; StrCmp, not IntCmp: an uninitialized var is "" and NSIS IntCmp does not rank "" below 1,
  ; which would skip every normal uninstall. tauri's own template uses LogicLib = (StrCmp).
  StrCmp $UpdateMode 1 demiurge_update_skip demiurge_start
  demiurge_start:
  StrCpy $R8 "=== uninstall: cache always, settings only if checked ==="
  Call un.DemiurgeLog

  ; tier 1 cache: unconditional
{cache}

  ; tier 2 settings: only when the app-data checkbox is checked
  StrCmp $DeleteAppDataCheckboxState 1 demiurge_settings_yes demiurge_settings_no
  demiurge_settings_yes:
{settings}
{bak}
  StrCpy $DemiurgeUninstMsg "$(DemiurgeUninstWiped)$DemiurgeShellHome\\userdata"
  MessageBox MB_OK|MB_ICONINFORMATION "$DemiurgeUninstMsg" /SD IDOK
  StrCpy $R8 "MSG   completion: settings removed, product kept"
  Call un.DemiurgeLog
  Goto demiurge_done
  demiurge_settings_no:
  StrCpy $R8 "SKIP  settings (checkbox off)"
  Call un.DemiurgeLog
  StrCpy $DemiurgeUninstMsg "$(DemiurgeUninstKeep)$DemiurgeShellHome"
  MessageBox MB_OK|MB_ICONINFORMATION "$DemiurgeUninstMsg" /SD IDOK
  StrCpy $R8 "MSG   completion: everything kept under shell home"
  Call un.DemiurgeLog
  Goto demiurge_done
  demiurge_update_skip:
  StrCpy $R8 "SKIP  update mode (keep runtime and data)"
  Call un.DemiurgeLog
  Goto demiurge_done
  demiurge_done:
  StrCpy $R8 "KEEP  product (repos, presets, cards, worldbooks, rag index, weights)"
  Call un.DemiurgeLog
!macroend
"""


def _assertions(content: str) -> None:
    for forbidden in ('RmDir /r "$DemiurgeShellHome"', 'Delete "$DemiurgeShellHome"'):
        if forbidden in content:
            raise SystemExit(f"生成脚本禁止删除整个壳 home：{forbidden}")
    userdata = data_layout.SCOPES[data_layout.SCOPE_USERDATA]
    for name, meta in userdata.items():
        if meta[0] in (data_layout.PRODUCT, data_layout.CONTAINER, data_layout.UNKNOWN):
            if f"userdata\\{name}" in content:
                raise SystemExit(f"产物/容器条目不该出现在删除面：{name}")
    # 卸载完成弹窗：两种结局各一条，文案只能来自语言文件；漏 /SD 会让静默卸载卡在模态框上。
    for reference in ("$(DemiurgeUninstKeep)", "$(DemiurgeUninstWiped)"):
        if reference not in content:
            raise SystemExit(f"卸载完成文案引用缺失：{reference}")
    boxes = [line for line in content.splitlines() if line.strip().startswith("MessageBox ")]
    if len(boxes) != 2 or not all(line.rstrip().endswith("/SD IDOK") for line in boxes):
        raise SystemExit(f"卸载完成弹窗应当恰好两条且都带 /SD IDOK：{boxes}")
    if "MessageBox" in content.split("demiurge_update_skip:", 1)[1]:
        raise SystemExit("升级模式覆盖安装中途不许弹卸载完成窗")
    content.encode("ascii")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="只比对生成物是否过期")
    args = parser.parse_args()

    content = render()
    _assertions(content)

    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != content:
            print(f"卸载钩子生成物已过期：{OUT.relative_to(ROOT)}")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"[hooks] 写出 {OUT.relative_to(ROOT)}（{len(content.splitlines())} 行）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
