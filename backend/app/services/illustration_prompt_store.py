def _config_path() -> Path:
    return DATA_DIR / "illustration_prompts.json"


def _read_config_file() -> dict:
    # 容错面刻意用 ERRORS_WITH_OS（含 OSError）：与 prose_style / palette_pref 同档，
    # 与列表型仓库（ERRORS_STANDARD）不同档。
    return json_file_store.read_dict(_config_path(), errors=json_file_store.ERRORS_WITH_OS)


def load_config() -> dict:
    """读用户态配置；缺文件 / 坏 JSON / 字段类型不符 → 回缺省判据。"""
    raw = _read_config_file()
    section = raw.get(CLIMAX_ANCHOR_KEY) if isinstance(raw, dict) else None
    section = section if isinstance(section, dict) else {}
    rubric = section.get("rubric")
    return {
        CLIMAX_ANCHOR_KEY: {
            "rubric": rubric if isinstance(rubric, str) and rubric.strip() else DEFAULT_CLIMAX_ANCHOR_RUBRIC,
        },
    }


def save_config(config: dict) -> dict:
    """落盘用户态配置，只保留合法字段（未知字段丢弃）；判据空串 / 非字符串 → 回缺省。"""
    section = config.get(CLIMAX_ANCHOR_KEY) if isinstance(config, dict) else None
    section = section if isinstance(section, dict) else {}
    rubric = section.get("rubric")
    rubric = rubric.strip() if isinstance(rubric, str) else ""
    clean = {
        CLIMAX_ANCHOR_KEY: {
            "rubric": rubric or DEFAULT_CLIMAX_ANCHOR_RUBRIC,
        },
    }
    json_file_store.write_json(_config_path(), clean)
    return clean


def effective_climax_anchor_rubric() -> str:
    """判据全文（**永不返回空串**：缺文件 / 坏 JSON / 留空都回缺省 v8）。

    判据档常开，故本函数不再承担「启用与否」的开关语义——它的结果只反映用户改过的判据文本。
    """
    return load_config()[CLIMAX_ANCHOR_KEY]["rubric"]


def settings_payload() -> dict:
    """设置对话框的 GET 响应体：当前配置 + 缺省判据 + 只读输出合同。

    `default_rubric` / `output_contract` 由后端给，**禁止前端复制真源**——与
    `image_prompt_profiles.profile_defaults`（质量词默认值）同一口径。
    """
    from app.services import scene_illustration

    return {
        **load_config(),
        "default_rubric": DEFAULT_CLIMAX_ANCHOR_RUBRIC,
        "output_contract": scene_illustration.ANCHOR_INTENT_CONTRACT,
    }
